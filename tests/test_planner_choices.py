"""
The path planners are searches with an explicit frontier whose order matters:
ties between equal costs are broken by the order vertices joined the frontier,
and ``verbose=True`` prints that order.  Implemented naively (lists searched
with ``in``, ``np.argmin`` over the frontier) they were O(V^2) or worse, and
the frontier is now a queue or heap with set lookups.  These tests pin the
results *and the verbose transcripts* that the original implementation gave,
so the faster one must make exactly the same choices.

The expectations were generated by the list-based planners that preceded it.
"""

import contextlib
