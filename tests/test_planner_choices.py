class TestPlannerChoices(unittest.TestCase):
    def check(self, make, planner):
        g, s, t = make()
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            result = getattr(g, f"path_{planner}")(s, t, verbose=True, summary=True)
        path, length, transcript = EXPECTED[(make.__name__, planner)]
        self.assertEqual([v.name for v in result[0]], path)
        self.assertEqual(result[1], length)
        self.assertEqual(buf.getvalue(), transcript)

    def test_grid_BFS(self):
        self.check(grid, "BFS")

    def test_grid_UCS(self):
        self.check(grid, "UCS")

    def test_grid_Astar(self):
        self.check(grid, "Astar")

    def test_reparent_BFS(self):
        self.check(reparent, "BFS")

    def test_reparent_UCS(self):
        self.check(reparent, "UCS")

    def test_reparent_Astar(self):
        self.check(reparent, "Astar")

    def test_reparenting_happens(self):
        # guard the guard: the transcript really does contain a reparent
        self.assertIn("reparent x", EXPECTED[("reparent", "UCS")][2])


if __name__ == "__main__":
    unittest.main()
