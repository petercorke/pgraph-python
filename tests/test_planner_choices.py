import unittest

from pgraph import DGraph, UGraph


def grid():
    # a 3 x 2 grid of unit squares plus the diagonal a-e: many equal costs
    g = UGraph(dim=2)
    coords = dict(a=(0, 0), b=(1, 0), c=(2, 0), d=(0, 1), e=(1, 1), f=(2, 1))
    v = {n: g.add_vertex(list(xy), name=n) for n, xy in coords.items()}
    for p, q in ["ab", "bc", "de", "ef", "ad", "be", "cf", "ae"]:
        g.add_edge(v[p], v[q], cost=1)
    return g, "a", "f"


def reparent():
    # x is first reached directly (cost 5), then more cheaply via y (1 + 1)
    g = DGraph(dim=2)
    v = {n: g.add_vertex([x, 0], name=n) for n, x in dict(s=0, y=1, x=2, t=3).items()}
    for p, q, c in [("s", "x", 5), ("s", "y", 1), ("y", "x", 1), ("x", "t", 1)]:
        g.add_edge(v[p], v[q], cost=c)
    return g, "s", "t"


